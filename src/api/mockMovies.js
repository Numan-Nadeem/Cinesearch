export function searchFallbackMovies(searchTerm, year = '', type = '', page = 1) {
  const query = (searchTerm || '').trim().toLowerCase();

  if (query === '__quota__') {
    return {
      Response: "False",
      Error: "Request limit reached!"
    };
  }

  const filtered = fallbackMovies.filter((movie) => {
    const matchesQuery =
      !query ||
      movie.Title.toLowerCase().includes(query) ||
      movie.Genre.toLowerCase().includes(query) ||
      movie.Director.toLowerCase().includes(query) ||
      movie.Actors.toLowerCase().includes(query);

    const matchesYear = !year || movie.Year.includes(String(year).trim());
    const normalizedType = (type || '').trim().toLowerCase();
    const matchesType =
      !normalizedType ||
      normalizedType === 'all' ||
      movie.Type.toLowerCase() === normalizedType;

    return matchesQuery && matchesYear && matchesType;
  });

  const pageSize = 10;
  const pageNum = Math.max(1, parseInt(page, 10) || 1);
  const startIndex = (pageNum - 1) * pageSize;
  const pageItems = filtered.slice(startIndex, startIndex + pageSize);

  if (pageItems.length === 0) {
    return {
      Response: "False",
      Error: "Movie not found!"
    };
  }

  return {
    Search: pageItems.map((m) => ({
      Title: m.Title,
      Year: m.Year,
      imdbID: m.imdbID,
      Type: m.Type,
      Poster: m.Poster,
      Genre: m.Genre,
      imdbRating: m.imdbRating
    })),
    totalResults: String(filtered.length),
    Response: "True"
  };
}

export function getFallbackMovieDetails(movieID) {
  if (!movieID || movieID === 'tt_quota') {
    return {
      Response: "False",
      Error: "Request limit reached!"
    };
  }

  const movie = fallbackMovies.find((m) => m.imdbID === movieID);
  if (movie) {
    return movie;
  }

  return {
    Response: "False",
    Error: "Incorrect IMDb ID."
  };
}

export function getFallbackTrending(genre = '') {
  const normalizedGenre = (genre || '').trim().toLowerCase();
  return fallbackMovies
    .filter((m) => {
      if (!normalizedGenre || normalizedGenre === 'all') return true;
      return m.Genre.toLowerCase().includes(normalizedGenre);
    })
    .sort((a, b) => (a.TrendingRank || 99) - (b.TrendingRank || 99))
    .slice(0, 8);
}
